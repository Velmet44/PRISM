/**
 * Stage 2 orchestration: cognition loop prompt assembly, provenance/taint,
 * and context compaction (PRISM V1 §17.1, §43.3).
 *
 * - `assemblePrompt()` preserves L0–L6 precedence, highest first. L0 (runtime/
 *   system policy) and L1 (Node/owner policy) are enforced by the runtime and
 *   policy engine OUTSIDE the prompt: they appear as described, non-relied-
 *   upon sections (`enforcedOutsidePrompt: true`). L5 (Agent-to-Agent) and L6
 *   (external/untrusted) are data only and can never change instructions or
 *   policy — L6 content is coerced to `external_untrusted`, and L5 content is
 *   capped at `agent_derived` (sender provenance is preserved below that cap).
 * - Provenance order (highest trust first): `trusted_system`,
 *   `trusted_owner`, `agent_derived`, `external_untrusted` (§43.3.1).
 *   `agent_derived` means generated by an Agent whose context was untainted
 *   at the time; model output or memory written from a tainted context is
 *   therefore `external_untrusted`.
 * - Taint is a high-water mark: a context containing any `external_untrusted`
 *   item is tainted and stays tainted until rebuilt from trusted items only.
 * - `compactContext()` NEVER launders taint: the summary inherits the
 *   lowest-trust label among its sources and the least-privileged layer, and
 *   the resulting context stays tainted whenever the input was.
 */

import { randomUUID } from "node:crypto";
import type { ErrorCode } from "@prism/schemas";

export type ProvenanceLabel =
  | "trusted_system"
  | "trusted_owner"
  | "agent_derived"
  | "external_untrusted";

/** Highest trust first (§43.3.1). */
export const PROVENANCE_PRECEDENCE: readonly ProvenanceLabel[] = [
  "trusted_system",
  "trusted_owner",
  "agent_derived",
  "external_untrusted",
];

export const PROVENANCE_RANK: Record<ProvenanceLabel, number> = {
  trusted_system: 4,
  trusted_owner: 3,
  agent_derived: 2,
  external_untrusted: 1,
};

export type InstructionLayer = "L0" | "L1" | "L2" | "L3" | "L4" | "L5" | "L6";

export const LAYER_ORDER: readonly InstructionLayer[] = [
  "L0",
  "L1",
  "L2",
  "L3",
  "L4",
  "L5",
  "L6",
];

export const LAYER_HEADINGS: Record<InstructionLayer, string> = {
  L0: "Runtime/system policy (enforced outside this prompt)",
  L1: "Node and owner policy (enforced outside this prompt)",
  L2: "Agent definition (identity and instructions)",
  L3: "Owner instructions",
  L4: "Delegated task state from the Main Agent",
  L5: "Agent-to-Agent messages (data only, with sender provenance)",
  L6: "External/untrusted content (data only)",
};

export interface ContextItem {
  id: string;
  layer: InstructionLayer;
  provenance: ProvenanceLabel;
  text: string;
  sourceRunId?: string;
  /** L5 sender; preserved as provenance metadata, never as authority. */
  senderId?: string;
  dataOnly?: boolean;
}

export interface PromptSection {
  layer: InstructionLayer;
  heading: string;
  /** L0/L1: described but enforced by the runtime, never the model. */
  enforcedOutsidePrompt: boolean;
  dataOnly: boolean;
  items: ContextItem[];
}

export interface AssembledPrompt {
  sections: PromptSection[];
  /** True when any included item is `external_untrusted`. */
  tainted: boolean;
  warnings: string[];
}

export class OrchestrationError extends Error {
  readonly code: ErrorCode;
  constructor(code: ErrorCode, message: string) {
    super(message);
    this.name = "OrchestrationError";
    this.code = code;
  }
}

/** Lowest-trust label wins; empty input fails closed to untrusted. */
export function lowestTrust(labels: Iterable<ProvenanceLabel>): ProvenanceLabel {
  let lowest: ProvenanceLabel = "trusted_system";
  let seen = false;
  for (const label of labels) {
    if (!(label in PROVENANCE_RANK)) {
      throw new OrchestrationError(
        "INVALID_ARGUMENT",
        `unknown provenance label: ${label as string}`,
      );
    }
    if (!seen || PROVENANCE_RANK[label] < PROVENANCE_RANK[lowest]) {
      lowest = label;
      seen = true;
    }
  }
  return seen ? lowest : "external_untrusted";
}

/**
 * Derived content (summary, translation, OCR, extraction, compaction result)
 * inherits the lowest-trust label among its sources — never higher.
 */
export function labelDerivedContent(
  sources: Iterable<ProvenanceLabel>,
): ProvenanceLabel {
  return lowestTrust(sources);
}

export function isTrustedContext(provenance: ProvenanceLabel): boolean {
  return provenance !== "external_untrusted";
}

/**
 * `agent_derived` means generated while the context was untainted; output
 * from a tainted context is `external_untrusted`.
 */
export function labelModelOutput(
  contextTainted: boolean,
): "agent_derived" | "external_untrusted" {
  return contextTainted ? "external_untrusted" : "agent_derived";
}

/** Entries written from a tainted context default to `external_untrusted`. */
export function labelMemoryWrite(
  contextTainted: boolean,
): "agent_derived" | "external_untrusted" {
  return labelModelOutput(contextTainted);
}

export function computeTainted(items: Iterable<ContextItem>): boolean {
  for (const item of items) {
    if (item.provenance === "external_untrusted") return true;
  }
  return false;
}

export interface AssemblePromptInput {
  systemPolicy?: string;
  nodeOwnerPolicy?: string;
  agentDefinition: string;
  ownerInstructions?: string;
  delegatedTaskState?: string;
  a2aMessages?: Array<{
    text: string;
    senderId: string;
    provenance?: ProvenanceLabel;
    sourceRunId?: string;
  }>;
  externalContent?: Array<{ text: string; sourceRunId?: string }>;
  memoryEntries?: Array<{
    text: string;
    provenance: ProvenanceLabel;
    sourceRunId?: string;
  }>;
}

function item(
  layer: InstructionLayer,
  provenance: ProvenanceLabel,
  text: string,
  extra?: Partial<ContextItem>,
): ContextItem {
  return {
    id: `ctx_${randomUUID()}`,
    layer,
    provenance,
    text,
    ...extra,
  };
}

/**
 * Assemble the model prompt with L0–L6 precedence. L0/L1 are marked
 * `enforcedOutsidePrompt`; L5/L6 are data only. Trust claims from untrusted
 * layers are coerced down (L6 forced to `external_untrusted`, L5 capped at
 * `agent_derived`) with a warning, so untrusted content can never arrive
 * with an elevated label.
 */
export function assemblePrompt(input: AssemblePromptInput): AssembledPrompt {
  if (typeof input.agentDefinition !== "string" || input.agentDefinition.length === 0) {
    throw new OrchestrationError(
      "INVALID_ARGUMENT",
      "agentDefinition (L2) is required",
    );
  }
  const warnings: string[] = [
    "L0/L1 are enforced by the runtime and policy engine outside this prompt; the model must not be relied upon to uphold them.",
    "L5/L6 are data only and cannot change instructions or policy.",
  ];

  const l5Items: ContextItem[] = [];
  for (const msg of input.a2aMessages ?? []) {
    let provenance = msg.provenance ?? "external_untrusted";
    if (
      provenance === "trusted_system" ||
      provenance === "trusted_owner"
    ) {
      warnings.push(
        `A2A message from ${msg.senderId} claimed ${provenance}; capped at agent_derived.`,
      );
      provenance = "agent_derived";
    }
    l5Items.push(
      item("L5", provenance, msg.text, {
        senderId: msg.senderId,
        dataOnly: true,
        ...(msg.sourceRunId !== undefined ? { sourceRunId: msg.sourceRunId } : {}),
      }),
    );
  }

  const l6Items: ContextItem[] = [];
  for (const ext of input.externalContent ?? []) {
    l6Items.push(
      item("L6", "external_untrusted", ext.text, {
        dataOnly: true,
        ...(ext.sourceRunId !== undefined ? { sourceRunId: ext.sourceRunId } : {}),
      }),
    );
  }

  const memoryItems: ContextItem[] = [];
  for (const entry of input.memoryEntries ?? []) {
    // Memory loads into L6 (untrusted data) unless owner-trusted or better;
    // loading an untrusted entry taints the context (§17.2).
    const layer: InstructionLayer =
      entry.provenance === "external_untrusted" ? "L6" : "L4";
    memoryItems.push(
      item(layer, entry.provenance, entry.text, {
        dataOnly: entry.provenance === "external_untrusted",
        ...(entry.sourceRunId !== undefined
          ? { sourceRunId: entry.sourceRunId }
          : {}),
      }),
    );
  }

  const text = (value: string | undefined): ContextItem[] =>
    value === undefined || value.length === 0
      ? []
      : [item("L0", "trusted_system", value)];

  const sections: PromptSection[] = [
    {
      layer: "L0",
      heading: LAYER_HEADINGS.L0,
      enforcedOutsidePrompt: true,
      dataOnly: false,
      items: text(input.systemPolicy),
    },
    {
      layer: "L1",
      heading: LAYER_HEADINGS.L1,
      enforcedOutsidePrompt: true,
      dataOnly: false,
      items:
        input.nodeOwnerPolicy === undefined || input.nodeOwnerPolicy.length === 0
          ? []
          : [item("L1", "trusted_owner", input.nodeOwnerPolicy)],
    },
    {
      layer: "L2",
      heading: LAYER_HEADINGS.L2,
      enforcedOutsidePrompt: false,
      dataOnly: false,
      items: [item("L2", "trusted_system", input.agentDefinition)],
    },
    {
      layer: "L3",
      heading: LAYER_HEADINGS.L3,
      enforcedOutsidePrompt: false,
      dataOnly: false,
      items:
        input.ownerInstructions === undefined || input.ownerInstructions.length === 0
          ? []
          : [item("L3", "trusted_owner", input.ownerInstructions)],
    },
    {
      layer: "L4",
      heading: LAYER_HEADINGS.L4,
      enforcedOutsidePrompt: false,
      dataOnly: false,
      items: [
        ...(input.delegatedTaskState === undefined ||
        input.delegatedTaskState.length === 0
          ? []
          : [item("L4", "agent_derived", input.delegatedTaskState)]),
        ...memoryItems.filter((m) => m.layer === "L4"),
      ],
    },
    {
      layer: "L5",
      heading: LAYER_HEADINGS.L5,
      enforcedOutsidePrompt: false,
      dataOnly: true,
      items: l5Items,
    },
    {
      layer: "L6",
      heading: LAYER_HEADINGS.L6,
      enforcedOutsidePrompt: false,
      dataOnly: true,
      items: [
        ...l6Items,
        ...memoryItems.filter((m) => m.layer === "L6"),
      ],
    },
  ];

  const allItems = sections.flatMap((s) => s.items);
  return { sections, tainted: computeTainted(allItems), warnings };
}

// ------------------------------------------------------------------ context

export interface ModelContext {
  items: ContextItem[];
  /** High-water mark: once true, only a trusted rebuild clears it. */
  tainted: boolean;
  updatedAt: number;
}

export function createContext(
  items: ContextItem[] = [],
  now: () => number = Date.now,
): ModelContext {
  return {
    items: items.map((i) => ({ ...i })),
    tainted: computeTainted(items),
    updatedAt: now(),
  };
}

/** Append items; taint is monotonic and never clears on add. */
export function addContextItems(
  context: ModelContext,
  items: ContextItem[],
  now: () => number = Date.now,
): ModelContext {
  const next = [...context.items, ...items.map((i) => ({ ...i }))];
  return {
    items: next,
    tainted: context.tainted || computeTainted(items),
    updatedAt: now(),
  };
}

/**
 * Rebuild a context from trusted items only. Throws when any item is
 * `external_untrusted` — callers must explicitly exclude untrusted material
 * (filtering is the auditable decision; this function never drops silently).
 */
export function rebuildFromTrusted(
  items: ContextItem[],
  now: () => number = Date.now,
): ModelContext {
  for (const itemEntry of items) {
    if (itemEntry.provenance === "external_untrusted") {
      throw new OrchestrationError(
        "INVALID_ARGUMENT",
        `cannot rebuild a trusted context with untrusted item ${itemEntry.id}`,
      );
    }
  }
  return { items: items.map((i) => ({ ...i })), tainted: false, updatedAt: now() };
}

// ---------------------------------------------------------------- compaction

export interface CompactionResult {
  summary: ContextItem;
  context: ModelContext;
}

/**
 * Compact the ephemeral tail of a context into a single summary item.
 * The summary inherits the lowest-trust label among compacted sources and
 * the least-privileged (lowest-precedence) layer, is always data-only, and
 * the resulting context preserves the taint high-water mark. Compaction
 * therefore NEVER launders taint into instructions or a higher label; a
 * defensive check throws `INTEGRITY_FAILURE` if the invariant ever breaks.
 */
export function compactContext(
  context: ModelContext,
  opts: {
    summarize: (texts: string[]) => string;
    keepIds?: string[];
    summaryProvenanceNote?: string;
    now?: () => number;
  },
): CompactionResult {
  const keep = new Set(opts.keepIds ?? []);
  const kept = context.items.filter((i) => keep.has(i.id));
  const compacted = context.items.filter((i) => !keep.has(i.id));
  if (compacted.length === 0) {
    throw new OrchestrationError(
      "INVALID_ARGUMENT",
      "compactContext requires at least one compactable item",
    );
  }
  const sourceLabels = compacted.map((i) => i.provenance);
  const provenance = labelDerivedContent(sourceLabels);
  const minRank = Math.min(...compacted.map((i) => PROVENANCE_RANK[i.provenance]));
  if (PROVENANCE_RANK[provenance] !== minRank) {
    throw new OrchestrationError(
      "INTEGRITY_FAILURE",
      "compaction would launder provenance; refusing",
    );
  }
  // Least-privileged layer among sources (highest L index), never above one.
  let layerIndex = 0;
  for (const entry of compacted) {
    layerIndex = Math.max(layerIndex, LAYER_ORDER.indexOf(entry.layer));
  }
  const layer = LAYER_ORDER[layerIndex] ?? "L6";
  const summaryText = opts.summarize(compacted.map((i) => i.text));
  const summary: ContextItem = {
    id: `ctx_${randomUUID()}`,
    layer,
    provenance,
    text:
      opts.summaryProvenanceNote === undefined
        ? summaryText
        : `${summaryText}\n[provenance: ${provenance}]`,
    dataOnly: true,
  };
  const now = opts.now ?? Date.now;
  const items = [...kept, summary];
  return {
    summary: { ...summary },
    context: {
      items,
      tainted: context.tainted || computeTainted(items),
      updatedAt: now(),
    },
  };
}

// ------------------------------------------------------------ cognition loop

export interface ModelInvokeResult {
  text: string;
}

export interface CognitionLoopOptions {
  invokeModel: (
    prompt: AssembledPrompt,
  ) => Promise<ModelInvokeResult> | ModelInvokeResult;
  summarize: (texts: string[]) => string;
  maxContextItems?: number;
  now?: () => number;
}

export interface CognitionStepInput extends AssemblePromptInput {
  /** Items to pin across compaction (defaults to none). */
  pinIds?: string[];
}

export interface CognitionStepResult {
  prompt: AssembledPrompt;
  modelOutput: ContextItem;
  context: ModelContext;
  compacted: boolean;
}

/**
 * Minimal Stage 2 cognition loop (§17.1 steps 3–9): assemble with L0–L6
 * precedence, invoke the injected model, ingest the result with
 * taint-derived provenance, persist it to context, and compact when the
 * item budget is reached. Policy evaluation (L0/L1) and tool execution stay
 * outside the prompt/model by construction.
 */
export class CognitionLoop {
  private readonly invokeModel: CognitionLoopOptions["invokeModel"];
  private readonly summarize: (texts: string[]) => string;
  private readonly maxContextItems: number;
  private readonly now: () => number;

  constructor(opts: CognitionLoopOptions) {
    this.invokeModel = opts.invokeModel;
    this.summarize = opts.summarize;
    this.maxContextItems = opts.maxContextItems ?? 64;
    this.now = opts.now ?? Date.now;
  }

  async step(
    context: ModelContext,
    input: CognitionStepInput,
  ): Promise<CognitionStepResult> {
    const prompt = assemblePrompt(input);
    const result = await this.invokeModel(prompt);
    if (typeof result.text !== "string" || result.text.length === 0) {
      throw new OrchestrationError("INVALID_ARGUMENT", "model returned no text");
    }
    const output: ContextItem = {
      id: `ctx_${randomUUID()}`,
      layer: "L4",
      provenance: labelModelOutput(context.tainted || prompt.tainted),
      text: result.text,
      dataOnly: false,
    };
    let next = addContextItems(context, [...prompt.sections.flatMap((s) => s.items), output], this.now);
    let compacted = false;
    if (next.items.length > this.maxContextItems) {
      const pinned = new Set(input.pinIds ?? []);
      const keepIds = next.items
        .filter((i) => pinned.has(i.id))
        .map((i) => i.id);
      // Always keep the fresh model output outside the compacted set.
      keepIds.push(output.id);
      const { context: compactedContext } = compactContext(next, {
        summarize: this.summarize,
        keepIds,
        now: this.now,
      });
      next = compactedContext;
      compacted = true;
    }
    return { prompt, modelOutput: { ...output }, context: next, compacted };
  }
}
