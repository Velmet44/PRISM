export type MachineName = keyof typeof MACHINE_TRANSITIONS;

export function machineStates(machine: string): readonly string[] {
  const states = MACHINE_STATES[machine];
  if (states === undefined) throw new Error(`unknown machine: ${machine}`);
  return states;
}

export function canTransition(
  machine: string,
  from: string,
  to: string,
): boolean {
  const transitions = MACHINE_TRANSITIONS[machine];
  if (transitions === undefined) throw new Error(`unknown machine: ${machine}`);
  return transitions.some(([f, t]) => f === from && t === to);
}

export function assertLegalTransition(
  machine: string,
  from: string,
  to: string,
): void {
  if (!canTransition(machine, from, to)) {
    throw new Error(`illegal transition: ${machine} ${from} -> ${to}`);
  }
}
